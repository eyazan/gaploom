#!/usr/bin/env python3
"""Merge daily-puzzle parts into data/daily/daily.json (sorted, de-duplicated by layout)."""
import json, sys, os
parts = sys.argv[1:]
items, seen = [], set()
for p in parts:
    for it in json.load(open(p)):
        key = "|".join(it["rows"])
        if key in seen:
            continue
        seen.add(key)
        items.append(it)
items.sort(key=lambda it: it["index"])
out = {"version": 1, "epoch": "2026-11-23", "note": "Generated by tools/make_daily.gd, verified by the solver.",
       "puzzles": [{"par": it["par"], "base": it["base"], "rows": it["rows"]} for it in items]}
os.makedirs(os.path.join(os.path.dirname(__file__), "..", "data", "daily"), exist_ok=True)
json.dump(out, open(os.path.join(os.path.dirname(__file__), "..", "data", "daily", "daily.json"), "w"), indent=1)
print(len(items), "puzzles")
